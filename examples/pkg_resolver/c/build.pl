% build.pl -- compile the frozen examples/pkg_resolver/resolver.pl plus
% the C-lane smoke wrappers into a WAM-C project. Clauses are re-asserted
% into `user` (the WAM compiler reads user:clause/2). Directives skipped.
%
% Fail closed: write_wam_c_project/3 currently comments
% `// Name/Arity: compilation failed` instead of failing (wam_c_target.pl
% around compile_predicates_for_project/3). Exit 0 from the generator is
% not evidence of a runnable resolver.
%
%   swipl -q -g main -t halt build.pl -- ../resolver.pl generated

:- use_module('../../../src/unifyweaver/targets/wam_c_target',
              [write_wam_c_project/3]).
:- use_module(library(filesex),
              [directory_file_path/3, copy_file/2, make_directory_path/1]).
:- use_module(library(readutil), [read_file_to_string/3]).
:- use_module(library(lists), [member/2, append/3]).
:- use_module(library(apply), [maplist/2]).

load_into_user(File, Preds) :-
    setup_call_cleanup(open(File, read, S), load_terms(S, [], Acc), close(S)),
    sort(Acc, Preds).

load_terms(S, Acc, Preds) :-
    read_term(S, T, []),
    (   T == end_of_file
    ->  Preds = Acc
    ;   T = (:- _)
    ->  load_terms(S, Acc, Preds)
    ;   pred_of_term(T, PA),
        assertz(user:T),
        load_terms(S, [PA|Acc], Preds)
    ).

pred_of_term((Head :- _), P/A) :- !, functor(Head, P, A).
pred_of_term(Head, P/A) :- functor(Head, P, A).

qualify_user(P/A, user:P/A).

required_smoke_preds([
    smoke_empty_requests/1,
    smoke_single_package/1,
    smoke_backtrack_conflict_deeper/1,
    smoke_unsatisfiable_missing/1,
    resolve/3
]).

c_copy_runtime_header(Dir) :-
    module_property(wam_c_target, file(TargetFile)),
    file_directory_name(TargetFile, TargetsDir),
    directory_file_path(TargetsDir, 'wam_c_runtime/wam_runtime.h', HdrSrc),
    directory_file_path(Dir, 'wam_runtime.h', HdrDst),
    copy_file(HdrSrc, HdrDst).

write_setup_inc(Preds, OutDir) :-
    directory_file_path(OutDir, 'setup_all.inc', Path),
    setup_call_cleanup(
        open(Path, write, S),
        write_setup_inc_stream(S, Preds),
        close(S)
    ).

write_setup_inc_stream(S, Preds) :-
    format(S, "/* Generated by build.pl -- do not edit. */~n", []),
    forall(member(_:N/A, Preds),
           format(S, "void setup_~w_~w(WamState* state);~n", [N, A])),
    format(S, "void setup_detected_wam_c_kernels(WamState* state);~n", []),
    format(S, "void setup_lowered_wam_c_helpers(WamState* state);~n~n", []),
    format(S, "static void setup_all_predicates(WamState *state) {~n", []),
    forall(member(_:N/A, Preds),
           format(S, "    setup_~w_~w(state);~n", [N, A])),
    format(S, "    setup_detected_wam_c_kernels(state);~n", []),
    format(S, "    setup_lowered_wam_c_helpers(state);~n", []),
    format(S, "}~n", []).

fail_closed_lib(OutDir, Preds) :-
    directory_file_path(OutDir, 'lib.c', LibPath),
    (   exists_file(LibPath)
    ->  true
    ;   format(user_error, "build.pl: missing ~w~n", [LibPath]),
        halt(1)
    ),
    read_file_to_string(LibPath, Lib, []),
    (   sub_string(Lib, _, _, _, ": compilation failed")
    ->  format(user_error,
               "build.pl: FAIL CLOSED -- lib.c contains omitted predicate compilation~n", []),
        fail_closed_list_omissions(Lib),
        halt(1)
    ;   true
    ),
    forall(member(_:N/A, Preds),
           (   format(atom(Needle), "void setup_~w_~w(WamState", [N, A]),
               (   sub_string(Lib, _, _, _, Needle)
               ->  true
               ;   format(user_error,
                          "build.pl: FAIL CLOSED -- missing ~w in lib.c~n",
                          [Needle]),
                   halt(1)
               )
           )).

fail_closed_list_omissions(Lib) :-
    split_string(Lib, "\n", "", Lines),
    forall(( member(Line, Lines),
             sub_string(Line, _, _, _, ": compilation failed")
           ),
           format(user_error, "  ~s~n", [Line])).

main :-
    current_prolog_flag(argv, Argv),
    source_file(main, HereFile),
    file_directory_name(HereFile, HereDir),
    (   Argv = [Src0, OutDir0|_]
    ->  Src = Src0, OutDir = OutDir0
    ;   directory_file_path(HereDir, '../resolver.pl', Src),
        directory_file_path(HereDir, 'generated', OutDir)
    ),
    directory_file_path(HereDir, 'smoke_wrappers.pl', WrapSrc),
    make_directory_path(OutDir),
    load_into_user(Src, ResolverPreds0),
    load_into_user(WrapSrc, WrapPreds0),
    append(ResolverPreds0, WrapPreds0, Preds0),
    sort(Preds0, PredsBare),
    maplist(qualify_user, PredsBare, Preds),
    required_smoke_preds(Required),
    forall(member(Req, Required),
           (   member(Req, PredsBare)
           ->  true
           ;   format(user_error, "build.pl: required predicate missing: ~q~n", [Req]),
               halt(1)
           )),
    length(Preds, N),
    format("build.pl: compiling ~w predicates from ~w + smoke wrappers~n",
           [N, Src]),
    write_wam_c_project(Preds,
        [no_kernels(true),
         lowered_helpers(false)],
        OutDir),
    fail_closed_lib(OutDir, Preds),
    c_copy_runtime_header(OutDir),
    write_setup_inc(Preds, OutDir),
    format("build.pl: wrote WAM C project under ~w/~n", [OutDir]).
